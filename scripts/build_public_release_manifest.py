FALLBACK = ("LICENSE_REVIEW", "Unclassified file inside a historical package; default to conservative review.")


def classify(rel):
    for pattern, tier, reason in RULES:
        if fnmatch.fnmatch(rel, pattern):
            return tier, reason
    if "historical_package" in rel:
        return FALLBACK
    return "PUBLIC_CORE", "Repo-authored file not matched by a specific rule; default to core (review before release)."


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def should_walk(dirname):
    return dirname not in IGNORE_DIR_NAMES


def main():
    rows = []
    for p in sorted(ROOT.rglob("*")):
        if not p.is_file():
            continue
        rel = str(p.relative_to(ROOT))
        parts = set(p.relative_to(ROOT).parts)
        if parts & IGNORE_DIR_NAMES:
            continue
        if any(rel.startswith(pfx) for pfx in IGNORE_PATH_PREFIXES):
            continue
        self_referential = rel == "docs/public_release_manifest_draft.csv"
        tier, reason = classify(rel)
        if self_referential:
            # This file must still be classified PUBLIC_CORE and copied into
            # the preview (scripts/validate_public_release.py reads it), but
            # it cannot record its own post-write hash (writing the row
            # changes the file). source_sha256 is left blank for this one
            # row only; scripts/validate_public_release.py's step2 excludes
            # this path from hash-consistency checks for the same reason.
            source_sha256 = ""
        else:
            source_sha256 = "" if tier == "SCRATCH_IGNORE" else sha(p)
        public_path = rel if tier in ("PUBLIC_CORE", "PUBLIC_OPTIONAL") else ""
        rows.append({
            "repo_path": rel, "tier": tier, "reason": reason,
            "source_sha256": source_sha256, "public_path_if_released": public_path,
        })

    out = ROOT / "docs/public_release_manifest_draft.csv"
    with open(out, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["repo_path", "tier", "reason", "source_sha256", "public_path_if_released"])
        w.writeheader()
        w.writerows(rows)

    from collections import Counter
    counts = Counter(r["tier"] for r in rows)
    print(f"{len(rows)} files classified -> {out.relative_to(ROOT)}")
    for tier in ("PUBLIC_CORE", "PUBLIC_OPTIONAL", "LICENSE_REVIEW", "ARCHIVAL_ONLY", "SCRATCH_IGNORE", "PUBLIC_RELEASE_PENDING_PERMISSION"):
        print(f"  {tier}: {counts.get(tier, 0)}")


if __name__ == "__main__":
    main()
