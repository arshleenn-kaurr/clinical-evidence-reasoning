#!/usr/bin/env python3
"""RELEASE TOOLING (not historical execution code). DRY-RUN ONLY.

Assembles a candidate public tree from docs/public_release_manifest_draft.csv
into dist/public_release_preview/ (or, with --v1-core, a further-scoped
dist/public_v1_preview/ using docs/public_v1_scope.csv). This is a PREVIEW,
never a publish step: it does not touch git, does not upload anything, and
never mutates the archival repository (read-only on every source file).

Rules:
  - copies only rows whose tier is PUBLIC_CORE or PUBLIC_OPTIONAL
  - skips LICENSE_REVIEW, ARCHIVAL_ONLY, SCRATCH_IGNORE
  - with --v1-core, additionally skips anything docs/public_v1_scope.csv
    marks DEFER_FROM_V1 (only V1_CORE + V1_SUPPORTING are copied)
  - writes <out_dir>/MANIFEST.csv recording, for every copied file, its
    source path, source sha256, copied sha256, and match
  - writes <out_dir>/PREVIEW_ONLY.txt
  - dist/ is gitignored; nothing here is committed or published automatically

Usage:
    python scripts/build_public_release.py [--core-only] [--v1-core]
"""
import argparse
import csv
import hashlib
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST_CSV = ROOT / "docs/public_release_manifest_draft.csv"
V1_SCOPE_CSV = ROOT / "docs/public_v1_scope.csv"
OUT_DIR_FULL = ROOT / "dist/public_release_preview"
OUT_DIR_V1 = ROOT / "dist/public_v1_preview"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--core-only", action="store_true", help="Copy only PUBLIC_CORE (skip PUBLIC_OPTIONAL).")
    ap.add_argument("--v1-core", action="store_true",
                    help="Build the scoped v1 preview (dist/public_v1_preview/): PUBLIC_CORE/PUBLIC_OPTIONAL "
                         "files AND docs/public_v1_scope.csv says V1_CORE or V1_SUPPORTING, i.e. excludes "
                         "DEFER_FROM_V1 as well as LICENSE_REVIEW/ARCHIVAL_ONLY/SCRATCH_IGNORE.")
    args = ap.parse_args()

    allowed_tiers = {"PUBLIC_CORE"} if args.core_only else {"PUBLIC_CORE", "PUBLIC_OPTIONAL"}
    out_dir = OUT_DIR_V1 if args.v1_core else OUT_DIR_FULL

    if not MANIFEST_CSV.exists():
        raise SystemExit(f"{MANIFEST_CSV} not found — run scripts/build_public_release_manifest.py first")
    with open(MANIFEST_CSV, newline="", encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh))

    v1_scope = {}
    if args.v1_core:
        if not V1_SCOPE_CSV.exists():
            raise SystemExit(f"{V1_SCOPE_CSV} not found — run scripts/build_public_v1_scope.py first")
        with open(V1_SCOPE_CSV, newline="", encoding="utf-8") as fh:
            v1_scope = {r["repo_path"]: r["v1_scope"] for r in csv.DictReader(fh)}

    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)

    copied = []
    skipped_by_tier = {}
    skipped_deferred = 0
    for row in rows:
        tier = row["tier"]
        if tier not in allowed_tiers:
            skipped_by_tier[tier] = skipped_by_tier.get(tier, 0) + 1
            continue
        if args.v1_core and v1_scope.get(row["repo_path"]) == "DEFER_FROM_V1":
            skipped_deferred += 1
            continue
        src = ROOT / row["repo_path"]
        if not src.exists():
            print(f"WARNING: listed but missing on disk, skipped: {row['repo_path']}")
            continue
        dst = out_dir / row["repo_path"]
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        s_src, s_dst = sha(src), sha(dst)
        copied.append({
            "public_path": row["repo_path"], "source_path": row["repo_path"],
            "source_sha256": s_src, "copied_sha256": s_dst, "match": str(s_src == s_dst).upper(),
        })

    with open(out_dir / "MANIFEST.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["public_path", "source_path", "source_sha256", "copied_sha256", "match"])
        w.writeheader()
        w.writerows(copied)

    scope_note = (
        "This is the V1-CORE SCOPED preview (python scripts/build_public_release.py --v1-core): a "
        "deliberately smaller first-release scope on top of the full public classification — see "
        "docs/public_v1_scope.md. Build the full public-eligible preview instead with "
        "`python scripts/build_public_release.py` (no flag) if you need everything PUBLIC_CORE/PUBLIC_OPTIONAL.\n\n"
        if args.v1_core else ""
    )
    (out_dir / "PREVIEW_ONLY.txt").write_text(
        f"{scope_note}This is a PREVIEW build only, generated by scripts/build_public_release.py.\n"
        "It has not been published anywhere. Nothing outside this directory was\n"
        "modified. Re-run the generating script to refresh it; do not edit these\n"
        "files directly, and do not treat this directory as a release artifact.\n"
    )

    mismatches = [c for c in copied if c["match"] != "TRUE"]
    print(f"Copied {len(copied)} files into {out_dir.relative_to(ROOT)} (PREVIEW ONLY, not published)")
    print(f"Skipped (not public): {skipped_by_tier}" + (f"; deferred from v1: {skipped_deferred}" if args.v1_core else ""))
    print(f"Hash mismatches: {len(mismatches)}")
    if mismatches:
        for m in mismatches:
            print("  MISMATCH:", m["public_path"])
        raise SystemExit(1)


if __name__ == "__main__":
    main()
